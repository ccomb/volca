            details check `shouldBe` ["land transformation is unbalanced: 10.000 m2 transformed from vs 4.000 m2 transformed to (60.00% apart)"]
            severities check `shouldBe` [WarningSev]

        it "passes an activity whose from and to areas match within rounding" $
            qcOffenders (qrLandTransformationBalance (reportOf (mkActivity "rotation" [reference breadFlow, bioExchange transFromFlow 10, bioExchange transToFlow 10.05])))
                `shouldBe` []

        it "sums several transformation lines on each side before comparing" $
            -- 6 + 4 from balances 10 to: the activity is fine only once summed.
            qcOffenders (qrLandTransformationBalance (reportOf (mkActivity "mosaic" [reference breadFlow, bioExchange transFromFlow 6, bioExchange transFromFlow 4, bioExchange transToFlow 10])))
                `shouldBe` []

        it "is not applicable to a database whose activities use no transformation flow" $ do
            let check = qrLandTransformationBalance (reportOf (mkActivity "bread" [reference breadFlow]))
            qcApplicable check `shouldBe` False
            qcOffenders check `shouldBe` []

    describe "oxygen demand order check" $ do
        it "flags an entry whose BOD5 exceeds its COD" $ do
            let act = mkActivity "effluent" [reference breadFlow, mkBio kgUnit bod5Flow 5, mkBio kgUnit codFlow 3]
                check = qrOxygenDemandOrder (reportOf act)
            details check `shouldBe` ["BOD5 (5.000) exceeds COD (3.000) in this entry - the biological oxygen demand cannot exceed the chemical"]
            severities check `shouldBe` [WarningSev]

        it "flags an entry whose DOC exceeds its TOC" $
            details (qrOxygenDemandOrder (reportOf (mkActivity "leachate" [reference breadFlow, mkBio kgUnit docFlow 2, mkBio kgUnit tocFlow 1])))
                `shouldBe` ["DOC (2.000) exceeds TOC (1.000) in this entry - the dissolved organic carbon cannot exceed the total"]

        it "passes an entry whose BOD5 is below its COD" $
            qcOffenders (qrOxygenDemandOrder (reportOf (mkActivity "effluent" [reference breadFlow, mkBio kgUnit bod5Flow 2, mkBio kgUnit codFlow 5])))
                `shouldBe` []

        it "does not flag a BOD5 present with no COD to compare it against" $
            qcOffenders (qrOxygenDemandOrder (reportOf (mkActivity "partial" [reference breadFlow, mkBio kgUnit bod5Flow 5])))
                `shouldBe` []

        it "is not applicable to a database with no oxygen-demand flow" $ do
            let check = qrOxygenDemandOrder (reportOf (mkActivity "bread" [reference breadFlow]))
            qcApplicable check `shouldBe` False
            qcOffenders check `shouldBe` []

