        it "accepts the zero-padded spelling of a valid CAS" $
            qcOffenders (qrInvalidCas (qualityReport "testdb" (casDbWith (Just "007439-92-1")))) `shouldBe` []

        it "flags a CAS that is not three dash-separated numbers" $
