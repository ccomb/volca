-- ---------------------------------------------------------------------------
-- UUID helpers: readable fixed identifiers.
-- ---------------------------------------------------------------------------

u :: String -> UUID
u suffix = read ("00000000-0000-0000-0000-0000000000" <> suffix)

kgUnit, unknownUnit, breadFlow, flourFlow, wasteFlow :: UUID
kgUnit = u "01"
unknownUnit = u "02"
breadFlow = u "03"
flourFlow = u "04"
wasteFlow = u "05"

m2Unit, transFromFlow, transToFlow :: UUID
m2Unit = u "06"
transFromFlow = u "07"
transToFlow = u "08"

bod5Flow, codFlow, docFlow, tocFlow, mercuryFlow :: UUID
bod5Flow = u "09"
codFlow = u "0c"
docFlow = u "0d"
tocFlow = u "0e"
mercuryFlow = u "0f"

actA, actB, actC, prodA, prodB, prodC :: UUID
actA = u "0a"
actB = u "0b"
actC = u "0c"
prodA = u "1a"
prodB = u "1b"
prodC = u "1c"

